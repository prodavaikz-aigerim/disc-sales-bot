def build_progress_bar(current_index: int, total: int, length: int = 10) -> str:
    """Цветная шкала прогресса (квадратики) — видно, сколько вопросов пройдено.

    current_index — индекс текущего вопроса (с 0), считаем его как "пройден"
    только после ответа, поэтому здесь используем current_index (уже
    отвеченные), не +1 — вызывающий код передаёт актуальное значение.
    """
    filled_count = round((current_index / total) * length) if total else 0
    filled_count = max(0, min(length, filled_count))
    bar = "🟨" * filled_count + "⬜" * (length - filled_count)
    return f"{bar} {current_index}/{total}"


def build_motivator_keyboard(qindex: int) -> InlineKeyboardMarkup:
    buttons = [
        InlineKeyboardButton(text=str(value), callback_data=f"manswer|{qindex}|{value}")
        for value in range(1, 6)
    ]
    return InlineKeyboardMarkup([buttons])


