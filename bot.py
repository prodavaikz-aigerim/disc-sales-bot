def split_for_telegram(text: str, limit: int = 3500) -> list:
    """Режет длинный текст на куски под лимит сообщения Telegram (4096 символов),
    стараясь резать по границам абзацев, а не посреди предложения.
    """
    if len(text) <= limit:
        return [text]

    chunks = []
    current = ""
    for paragraph in text.split("\n\n"):
        candidate = f"{current}\n\n{paragraph}" if current else paragraph
        if len(candidate) > limit and current:
            chunks.append(current)
            current = paragraph
        else:
            current = candidate
    if current:
        chunks.append(current)
    return chunks


async def handle_confirm_payment(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query

    if ADMIN_CHAT_ID and str(query.message.chat.id) != str(ADMIN_CHAT_ID):
        await query.answer(text="Недостаточно прав", show_alert=True)
        return

    await query.answer()

    try:
        _, target_id_str = query.data.split("|")
    except ValueError:
        return

    pending = context.bot_data.get("pending", {})
    record = pending.pop(target_id_str, None)

    if record is None:
        await edit_admin_message(query, "⚠️ Заявка не найдена — возможно, уже обработана.")
        return

    target_id = int(target_id_str)
    disc_scores = record["disc_scores"]
    motivator_scores = record["motivator_scores"]

    # Сразу показываем промежуточный статус — генерация через Claude API
    # обычно занимает 10-30 секунд, и без этого сообщения кажется, что
    # кнопка зависла.
    await edit_admin_message(query, "⏳ Генерирую отчёт и отправляю... (отчёт стал длиннее, обычно 30-90 секунд, иногда до 2-3 минут)")

    # Пытаемся сгенерировать настоящий синтез через Claude API (список из 15
    # секций содержания). Если не получилось (нет ключа, ошибка сети, модель
    # вернула не 15 частей) — подстраховываемся склеенной версией двух
    # статических полных отчётов, чтобы клиент в любом случае получил
    # результат. И в том, и в другом случае итоговый текст — валидный HTML
    # (заголовки жирным мы добавляем сами, содержание экранировано).
    sections, error_reason = await generate_full_report(disc_scores, motivator_scores)
    used_fallback = sections is None
    if sections is None:
        report_text = (
            format_full_result_text(disc_scores)
            + "\n\n"
            + format_motivator_full_text(motivator_scores)
        )
    else:
        report_text = format_report_html(sections)

    telegram_ok = True
    try:
        await context.bot.send_message(
            chat_id=target_id,
            text="🎉 Оплата подтверждена! Вот твой полный профиль продавца.",
        )
        for chunk in split_for_telegram(report_text):
            await context.bot.send_message(chat_id=target_id, text=chunk, parse_mode=ParseMode.HTML)

        academy_cta_text = format_academy_cta_text()
        academy_buttons = InlineKeyboardMarkup(
            [
                [InlineKeyboardButton(CHANNEL_BUTTON_TEXT, url=CHANNEL_URL)],
                [InlineKeyboardButton(COURSE_BUTTON_TEXT, url=COURSE_URL)],
            ]
        )
        await context.bot.send_message(
            chat_id=target_id,
            text=academy_cta_text,
            parse_mode=ParseMode.HTML,
            reply_markup=academy_buttons,
        )
    except TelegramError:
        logger.exception("Не удалось отправить отчёт пользователю %s в Telegram", target_id)
        telegram_ok = False

    status_lines = [f"✅ Отправлено: {record.get('username') or record.get('full_name') or target_id}"]
    status_lines.append(f"Telegram: {'ok' if telegram_ok else '⚠️ не доставлено (бот заблокирован?)'}")
    if used_fallback:
        status_lines.append(f"⚠️ Отправлена склеенная версия ({error_reason})")
    await edit_admin_message(query, "\n".join(status_lines))


async def edit_admin_message(query, new_text: str):
    """Правит сообщение админу после подтверждения — медиа с подписью (фото
    или документ) или обычный текст.
    """
    if query.message.photo or query.message.document:
        await query.edit_message_caption(caption=new_text)
    else:
        await query.edit_message_text(new_text)


async def pending_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Список заявок, ожидающих подтверждения — на случай, если пропустила уведомление."""
    if ADMIN_CHAT_ID and str(update.effective_chat.id) != str(ADMIN_CHAT_ID):
        return

    pending = context.bot_data.get("pending", {})
    if not pending:
        await update.message.reply_text("Нет заявок, ожидающих подтверждения.")
        return

    for uid, record in pending.items():
        contact = f"@{record['username']}" if record.get("username") else record.get("full_name", uid)
        button = InlineKeyboardMarkup(
            [[InlineKeyboardButton("✅ Подтвердить и отправить", callback_data=f"confirm|{uid}")]]
        )
        caption = contact
        if record.get("receipt_file_id"):
            if record.get("receipt_is_photo", True):
                await update.message.reply_photo(
                    photo=record["receipt_file_id"], caption=caption, reply_markup=button
                )
            else:
                await update.message.reply_document(
                    document=record["receipt_file_id"], caption=caption, reply_markup=button
                )
        else:
            await update.message.reply_text(caption, reply_markup=button)


def format_result_text(scores: dict) -> str:
    """Бесплатный результат — законченный мини-разбор, но осознанно неполный.

    Структура (по примеру, который утвердила Айгерим):
      - профиль (2 ведущих психотипа + краткое связное описание)
      - 1 зона риска (не полный список, только самая характерная)
      - 1 главный совет (не полный список рекомендаций)
      - явная рамка "это только 20% профиля"

    Полный список "зон роста" и "рекомендаций" остаётся в PROFILES и
    используется в format_full_result_text() — платной версии.
    """
    ranked = sorted(scores.items(), key=lambda item: item[1], reverse=True)
    top1_code, _ = ranked[0]
    top2_code, _ = ranked[1]

    top1 = PROFILES[top1_code]
    top2 = PROFILES[top2_code]

    lines = []
    lines.append("🎯 <b>Твой результат готов!</b>\n")
    lines.append(
        f"<b>Твой профиль: {top1['emoji']} {top1['name']} "
        f"+ {top2['emoji']} {top2['name']}</b>\n"
    )

    # Краткое связное описание из "сильных сторон" обоих типов
    summary = " ".join(
        s.capitalize() + "."
        for profile in (top1, top2)
        for s in profile["strengths"][:1]
    )
    lines.append(summary)
    lines.append("")

    # 1 зона риска — берём первую (самую характерную) у ведущего типа
    lines.append(f"<b>Твоя зона риска:</b> {top1['weaknesses'][0]}.")
    lines.append("")

    # 1 главный совет — берём первую рекомендацию у ведущего типа
    lines.append(f"<b>Главный совет:</b> {top1['recommendations'][0]}.")
    lines.append("")

    lines.append(
        "Помни: нет «плохих» и «хороших» психотипов — есть особенности, "
        "которые можно использовать в свою пользу, если знать, как именно."
    )
    lines.append("")
    lines.append("📊 Это только 20% твоего профиля.")

    return "\n".join(lines)


